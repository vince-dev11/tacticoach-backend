#!/usr/bin/env node
// DISPOSABLE-EMAIL (25 Nov 2026): refresh the list of throwaway email domains
// (yopmail, mailinator, 10minutemail …) that can't sign up or request early
// access. Source: the community list used by PyPI and others —
// https://github.com/disposable-email-domains/disposable-email-domains (CC0).
// Run about once a month, commit the result:
//
//   node scripts/update-disposable-domains.mjs            # download the latest
//   node scripts/update-disposable-domains.mjs list.txt   # from a saved copy
//
// Writes src/lib/disposable-domains.ts. Domains in NEVER_BLOCK (real mail
// providers and privacy relays that forward to a real inbox) are always kept out.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = 'https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf'
const { NEVER_BLOCK } = await import(join(ROOT, 'scripts', 'never-block-domains.mjs'))

const text = process.argv[2]
  ? readFileSync(process.argv[2], 'utf8')
  : await (await fetch(SOURCE, { signal: AbortSignal.timeout(30_000) })).text()
const domains = [...new Set(text.split(/\r?\n/).map((l) => l.trim().toLowerCase()).filter((l) => l && !l.startsWith('#') && /^[a-z0-9.-]+\.[a-z0-9-]+$/.test(l)))]
  .filter((d) => !NEVER_BLOCK.includes(d))
  .sort()
if (domains.length < 1000) throw new Error(`Only ${domains.length} domains — the download looks wrong; nothing written.`)

const out = `// GENERATED by scripts/update-disposable-domains.mjs — do not edit by hand.
// ${domains.length} throwaway email domains (CC0, github.com/disposable-email-domains/disposable-email-domains).
// Updated ${new Date().toISOString().slice(0, 10)}.
export const DISPOSABLE_DOMAINS = ${JSON.stringify(domains.join('\n'))}
`
writeFileSync(join(ROOT, 'src', 'lib', 'disposable-domains.ts'), out)
console.log(`wrote ${domains.length} domains`)
